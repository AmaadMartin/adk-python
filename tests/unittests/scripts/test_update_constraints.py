"""Tests for the snapshot date contract of ``scripts/update_constraints.sh``.

Check mode re-resolves each ``constraints-<ver>.txt`` against the snapshot date
recorded in the file's own header, and asserts the result is byte-identical. A
header that records no single ``--exclude-newer YYYY-MM-DD`` date leaves
nothing to verify the pins against, so check mode must reject that file before
it resolves anything. Update mode owns the date and repairs such a header.

The script runs as a subprocess against a stub ``uv``, so no test reaches PyPI.
"""

from __future__ import annotations

import pathlib
import re
import subprocess
import sys

import pytest

pytestmark = pytest.mark.skipif(
    sys.platform.startswith('win'), reason='POSIX shell script.'
)

_SCRIPT = (
    pathlib.Path(__file__).resolve().parents[3]
    / 'scripts'
    / 'update_constraints.sh'
)
_PYTHON_VERSIONS = ('3.10', '3.11', '3.12', '3.13', '3.14')
# The one version each test makes unreadable; the other four stay well-formed.
_BROKEN_VERSION = '3.12'
_PIN = 'typing-extensions==4.12.2'
_RECORDED_DATE = '2026-01-02'

# A stub `uv` that appends its argv to a log and writes the file named by `-o`
# instead of resolving against PyPI. The script keeps only `tail -n +3` of that
# output, hence the two throwaway header lines.
_UV_STUB = """#!/bin/bash
printf '%s\\n' "$*" >> "{call_log}"
while [ "$#" -gt 0 ]; do
  if [ "$1" = "-o" ]; then
    printf '# header\\n# command\\n{pin}\\n' > "$2"
    exit 0
  fi
  shift
done
exit 1
"""


def _header(version: str, flags: str) -> str:
  """Returns the two header lines recording a command that carries ``flags``."""
  return (
      '# This file was autogenerated by uv via the following command:\n'
      '#    uv pip compile pyproject.toml --all-extras --python-version'
      f' {version}{flags} --index-url'
      f' https://pypi.org/simple -o constraints-{version}.txt\n'
  )


def _generated_file(version: str, date: str) -> str:
  """Returns the exact bytes the script writes for ``version`` and ``date``."""
  return _header(version, f' --exclude-newer {date}') + f'{_PIN}\n'


# Contents for constraints-3.12.txt whose header records no single snapshot
# date. The last two are the sharp ones: an emptiness test accepts them, and
# the two-line value then expands into stray argv on the uv command line.
_UNREADABLE_HEADERS = {
    'snapshot-flag-absent': _header(_BROKEN_VERSION, '') + f'{_PIN}\n',
    'file-empty': '',
    'date-not-zero-padded': (
        _header(_BROKEN_VERSION, ' --exclude-newer 2026-7-1') + f'{_PIN}\n'
    ),
    'two-recorded-dates': (
        _generated_file(_BROKEN_VERSION, '2026-01-02')
        + _generated_file(_BROKEN_VERSION, '2026-03-04')
    ),
}

_NO_SNAPSHOT_DATE = (
    f'❌ constraints-{_BROKEN_VERSION}.txt has no single'
    " '--exclude-newer YYYY-MM-DD' snapshot date in its header,"
)


def _constraints(tmp_path: pathlib.Path, version: str) -> pathlib.Path:
  return tmp_path / f'constraints-{version}.txt'


def _write_all(tmp_path: pathlib.Path, date: str) -> None:
  """Writes a well-formed constraints file for every supported version."""
  for version in _PYTHON_VERSIONS:
    _constraints(tmp_path, version).write_text(_generated_file(version, date))


class _Run:
  """The outcome of one script invocation."""

  def __init__(
      self, process: subprocess.CompletedProcess[str], call_log: pathlib.Path
  ) -> None:
    self.returncode = process.returncode
    self.stdout = process.stdout
    self.stderr = process.stderr
    self.uv_calls = (
        call_log.read_text().splitlines() if call_log.exists() else []
    )

  def snapshot_date_for(self, version: str) -> str | None:
    """Returns the date `uv` was asked to resolve ``version`` against."""
    for call in self.uv_calls:
      match = re.search(
          rf'--python-version {version} --exclude-newer'
          rf' (\d{{4}}-\d{{2}}-\d{{2}}) ',
          call,
      )
      if match:
        return match.group(1)
    return None


def _run(tmp_path: pathlib.Path, *args: str) -> _Run:
  """Runs the script in an isolated CWD against a stub `uv`.

  Setting HOME is mandatory: the script prepends `$HOME/.local/bin` to PATH, so
  leaving the developer's real HOME in place would let a real `uv` shadow the
  stub and make these tests pass for the wrong reason.
  """
  (tmp_path / 'pyproject.toml').write_text(
      '[project]\nname = "x"\nversion = "0.1"\n'
  )
  stub_dir = tmp_path / 'bin'
  stub_dir.mkdir(exist_ok=True)
  call_log = tmp_path / 'uv-calls.log'
  stub = stub_dir / 'uv'
  stub.write_text(_UV_STUB.format(call_log=call_log, pin=_PIN))
  stub.chmod(0o755)
  process = subprocess.run(
      ['bash', str(_SCRIPT), *args],
      cwd=tmp_path,
      env={'PATH': f'{stub_dir}:/usr/bin:/bin', 'HOME': str(tmp_path)},
      capture_output=True,
      text=True,
      check=False,
  )
  return _Run(process, call_log)


@pytest.mark.parametrize(
    'content', _UNREADABLE_HEADERS.values(), ids=_UNREADABLE_HEADERS.keys()
)
def test_check_mode_rejects_a_header_without_a_readable_snapshot_date(
    tmp_path: pathlib.Path, content: str
) -> None:
  _write_all(tmp_path, _RECORDED_DATE)
  unreadable = _constraints(tmp_path, _BROKEN_VERSION)
  unreadable.write_text(content)

  result = _run(tmp_path, '--check')

  assert result.returncode == 1
  assert _NO_SNAPSHOT_DATE in result.stdout
  # The file is not stale, so the stale diagnosis names the wrong remedy.
  assert f'constraints-{_BROKEN_VERSION}.txt is OUT OF DATE!' not in (
      result.stdout
  )
  assert unreadable.read_text() == content
  # Resolving would verify the pins against the live index, and a second
  # recorded date would splice a bare word into the uv command line.
  assert not [c for c in result.uv_calls if _BROKEN_VERSION in c]
  assert 'command not found' not in result.stderr
  # The remaining versions are still checked.
  assert len(result.uv_calls) == len(_PYTHON_VERSIONS) - 1
  for version in _PYTHON_VERSIONS:
    if version != _BROKEN_VERSION:
      assert f'✅ constraints-{version}.txt is up-to-date.' in result.stdout


def test_check_mode_resolves_against_the_recorded_snapshot_date(
    tmp_path: pathlib.Path,
) -> None:
  _write_all(tmp_path, _RECORDED_DATE)

  result = _run(tmp_path, '--check')

  assert result.returncode == 0
  assert _NO_SNAPSHOT_DATE not in result.stdout
  assert len(result.uv_calls) == len(_PYTHON_VERSIONS)
  for version in _PYTHON_VERSIONS:
    assert result.snapshot_date_for(version) == _RECORDED_DATE


def test_check_mode_reports_missing_files_without_resolving(
    tmp_path: pathlib.Path,
) -> None:
  result = _run(tmp_path, '--check')

  assert result.returncode == 1
  assert _NO_SNAPSHOT_DATE not in result.stdout
  assert not result.uv_calls
  for version in _PYTHON_VERSIONS:
    assert f'❌ constraints-{version}.txt is missing!' in result.stdout


def test_update_mode_regenerates_a_file_with_a_malformed_header(
    tmp_path: pathlib.Path,
) -> None:
  """Update mode owns the date, so it repairs a header it cannot read."""
  _write_all(tmp_path, _RECORDED_DATE)
  malformed = _constraints(tmp_path, _BROKEN_VERSION)
  malformed.write_text(_UNREADABLE_HEADERS['snapshot-flag-absent'])

  result = _run(tmp_path)

  assert _NO_SNAPSHOT_DATE not in result.stdout
  assert (
      f'🔄 constraints-{_BROKEN_VERSION}.txt was OUT OF DATE. Updating it'
      ' automatically...'
      in result.stdout
  )
  assert len([c for c in result.uv_calls if _BROKEN_VERSION in c]) == 1
  # Asserting a literal `today - 4d` would race a midnight rollover between
  # the script's clock and the test's, so read back what the script used.
  date_used = result.snapshot_date_for(_BROKEN_VERSION)
  assert date_used is not None
  assert malformed.read_text() == _generated_file(_BROKEN_VERSION, date_used)
