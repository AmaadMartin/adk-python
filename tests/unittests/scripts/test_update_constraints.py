"""Behaviour tests for scripts/update_constraints.sh under bash strict mode.

The script is driven as a real subprocess against a stub ``uv``, so nothing
here reaches the network. Every test asserts that no read of an unset
parameter aborts the run.
"""

from __future__ import annotations

import dataclasses
import pathlib
import re
import subprocess

import pytest

_SCRIPT = (
    pathlib.Path(__file__).resolve().parents[3]
    / 'scripts'
    / 'update_constraints.sh'
)

# Kept in step with PYTHON_VERSIONS in the script.
_PYTHON_VERSIONS = ('3.10', '3.11', '3.12', '3.13', '3.14')

# The single requirement the stub uv resolves to.
_STUB_PIN = 'pinned-package==1.0.0'

# A pin the stub never produces, so a file carrying it is out of date.
_STALE_PIN = 'pinned-package==0.9.0'

# Fails only when the script passes the stabilization constraint file.
_FAIL_WITH_CONSTRAINT = """case " $* " in
  *' --constraint '*) exit 1 ;;
esac"""


def _generation_command(ver: str, date: str | None) -> str:
  """Returns the command the script records in a constraints file header."""
  command = f'uv pip compile pyproject.toml --all-extras --python-version {ver}'
  if date is not None:
    command += f' --exclude-newer {date}'
  return command + (
      f' --index-url https://pypi.org/simple -o constraints-{ver}.txt'
  )


def _constraints_body(ver: str, date: str | None, pin: str) -> str:
  return (
      '# This file was autogenerated by uv via the following command:\n'
      f'#    {_generation_command(ver, date)}\n'
      f'{pin}\n'
  )


def _exclude_newer(call: str) -> str | None:
  """Returns the --exclude-newer date in a recorded uv call, if any."""
  match = re.search(r'--exclude-newer (\S+)', call)
  return match.group(1) if match else None


def _called_version(call: str) -> str | None:
  """Returns the Python version a recorded uv call writes output for."""
  match = re.search(r'-o constraints-(\d+\.\d+)\.txt', call)
  return match.group(1) if match else None


@dataclasses.dataclass(frozen=True)
class _Workspace:
  """A throwaway repository root the script runs against."""

  root: pathlib.Path
  uv_log: pathlib.Path

  def install_uv_stub(self, failure_block: str = '') -> None:
    """Installs a stub uv that logs its argv and writes the -o target."""
    stub = self.root / 'bin' / 'uv'
    stub.parent.mkdir(exist_ok=True)
    stub.write_text(
        f"""#!/bin/bash
printf '%s\\n' "$*" >> '{self.uv_log}'
{failure_block}
output=''
want_output=0
for arg in "$@"; do
  if [ "$want_output" -eq 1 ]; then
    output="$arg"
    want_output=0
  elif [ "$arg" = '-o' ]; then
    want_output=1
  fi
done
: > "$output"
echo '# stub header line one, dropped by the script' >> "$output"
echo '# stub header line two, dropped by the script' >> "$output"
echo '{_STUB_PIN}' >> "$output"
""",
        encoding='utf-8',
    )
    stub.chmod(0o755)

  def write_constraints(
      self, ver: str, date: str | None, pin: str = _STUB_PIN
  ) -> None:
    (self.root / f'constraints-{ver}.txt').write_text(
        _constraints_body(ver, date, pin), encoding='utf-8'
    )

  def read_constraints(self, ver: str) -> str:
    return (self.root / f'constraints-{ver}.txt').read_text(encoding='utf-8')

  def run(self, *args: str) -> subprocess.CompletedProcess[str]:
    return subprocess.run(
        ['bash', str(_SCRIPT), *args],
        cwd=self.root,
        # An explicit HOME is mandatory: the script prepends $HOME/.local/bin
        # to PATH, so the developer's real uv could otherwise shadow the stub.
        env={
            'PATH': f'{self.root / "bin"}:/usr/bin:/bin',
            'HOME': str(self.root),
        },
        capture_output=True,
        text=True,
        encoding='utf-8',
        check=False,
    )

  def uv_calls(self) -> list[str]:
    if not self.uv_log.exists():
      return []
    return self.uv_log.read_text(encoding='utf-8').splitlines()


@pytest.fixture
def workspace(tmp_path: pathlib.Path) -> _Workspace:
  space = _Workspace(root=tmp_path, uv_log=tmp_path / 'uv_calls.log')
  (tmp_path / 'pyproject.toml').write_text(
      '[project]\nname = "stub"\nversion = "0.0.0"\n', encoding='utf-8'
  )
  space.install_uv_stub()
  return space


def _assert_no_unset_parameter(
    result: subprocess.CompletedProcess[str],
) -> None:
  assert 'unbound variable' not in result.stderr


def test_check_mode_resolves_against_the_recorded_snapshot_date(
    workspace: _Workspace,
) -> None:
  dates = {ver: f'2026-01-1{i}' for i, ver in enumerate(_PYTHON_VERSIONS)}
  for ver, date in dates.items():
    workspace.write_constraints(ver, date)

  result = workspace.run('--check')

  _assert_no_unset_parameter(result)
  assert result.returncode == 0, result.stdout
  calls = workspace.uv_calls()
  assert len(calls) == len(_PYTHON_VERSIONS)
  assert {_called_version(c): _exclude_newer(c) for c in calls} == dates


def test_check_mode_survives_a_header_with_no_snapshot_date(
    workspace: _Workspace,
) -> None:
  # The stale pin makes this file out of date whichever diagnosis the script
  # reaches, so the assertions below do not depend on how a dateless header
  # is reported.
  workspace.write_constraints('3.10', date=None, pin=_STALE_PIN)
  for ver in _PYTHON_VERSIONS[1:]:
    workspace.write_constraints(ver, '2026-01-15')

  result = workspace.run('--check')

  _assert_no_unset_parameter(result)
  assert result.returncode == 1
  for ver in _PYTHON_VERSIONS[1:]:
    assert f'✅ constraints-{ver}.txt is up-to-date.' in result.stdout


def test_update_mode_with_no_arguments_rewrites_every_file(
    workspace: _Workspace,
) -> None:
  result = workspace.run()

  _assert_no_unset_parameter(result)
  assert result.returncode == 1
  calls = workspace.uv_calls()
  # Read the date back out of the stub's argv: asserting a literal `today - 4d`
  # would race a midnight rollover.
  dates = {_exclude_newer(call) for call in calls}
  assert len(dates) == 1
  computed_date = dates.pop()
  assert computed_date is not None
  assert re.fullmatch(r'\d{4}-\d{2}-\d{2}', computed_date)
  for ver in _PYTHON_VERSIONS:
    assert workspace.read_constraints(ver) == _constraints_body(
        ver, computed_date, _STUB_PIN
    )


def test_an_unrecognized_argument_is_ignored(workspace: _Workspace) -> None:
  result = workspace.run('--bogus')

  _assert_no_unset_parameter(result)
  assert result.returncode == 1
  assert len(workspace.uv_calls()) == len(_PYTHON_VERSIONS)
  for ver in _PYTHON_VERSIONS:
    assert _STUB_PIN in workspace.read_constraints(ver)


def test_check_mode_reports_a_missing_file_without_resolving(
    workspace: _Workspace,
) -> None:
  result = workspace.run('--check')

  _assert_no_unset_parameter(result)
  assert result.returncode == 1
  for ver in _PYTHON_VERSIONS:
    assert f'❌ constraints-{ver}.txt is missing!' in result.stdout
  assert workspace.uv_calls() == []


def test_check_mode_reports_a_failed_resolution(workspace: _Workspace) -> None:
  workspace.install_uv_stub(failure_block='exit 1')
  for ver in _PYTHON_VERSIONS:
    workspace.write_constraints(ver, '2026-01-15')

  result = workspace.run('--check')

  _assert_no_unset_parameter(result)
  assert result.returncode == 1
  for ver in _PYTHON_VERSIONS:
    assert (
        '❌ Resolution failed with stable constraints for'
        f' constraints-{ver}.txt.'
        in result.stdout
    )
  # The loop visits every version: set -e stays suspended inside `if ! eval`.
  assert len(workspace.uv_calls()) == len(_PYTHON_VERSIONS)


def test_update_mode_retries_without_the_stable_constraint(
    workspace: _Workspace,
) -> None:
  workspace.install_uv_stub(failure_block=_FAIL_WITH_CONSTRAINT)
  workspace.write_constraints('3.10', '2026-01-15', pin=_STALE_PIN)

  result = workspace.run()

  _assert_no_unset_parameter(result)
  assert result.returncode == 1
  assert '⚠️ Resolution failed with stable constraints.' in result.stdout
  assert _STUB_PIN in workspace.read_constraints('3.10')
  # Two calls for 3.10: the constrained attempt, then the retry without it.
  calls = [c for c in workspace.uv_calls() if _called_version(c) == '3.10']
  assert len(calls) == 2
  assert '--constraint' in calls[0]
  assert '--constraint' not in calls[1]
